// Converts design/img sources to public/images as AVIF + WebP at explicit widths (never upscaled)
// and writes src/content/images.ts with each output's real width and height.
import sharp from "sharp";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const JOBS = [
  { key: "hero", name: "hero", src: "design/img/hero.jpg", widths: [1376, 768] },
  { key: "panelTop", name: "panel-top", src: "design/img/panel-top.jpg", widths: [256] },
  // Shop preview tiles: 1024px squares shown at most 384px wide, so 640 covers 1.5x screens.
  { key: "productPanel", name: "product-panel", src: "design/img/product-panel.jpg", widths: [640] },
  { key: "productInverter", name: "product-inverter", src: "design/img/product-inverter.jpg", widths: [640] },
  { key: "productBattery", name: "product-battery", src: "design/img/product-battery.jpg", widths: [640] },
];
const FORMATS = { avif: { quality: 55, effort: 6 }, webp: { quality: 78, effort: 6 } };

mkdirSync("public/images", { recursive: true });
const meta = {};
for (const { key, name, src, widths } of JOBS) {
  const srcW = (await sharp(src).metadata()).width;
  meta[key] = {};
  for (const w of widths) {
    if (w > srcW) throw new Error(`${src}: ${w}px would upscale a ${srcW}px source`);
    for (const [fmt, opts] of Object.entries(FORMATS)) {
      const file = `public/images/${name}-${w}.${fmt}`;
      const info = await sharp(src).resize({ width: w, withoutEnlargement: true })[fmt](opts).toFile(file);
      meta[key][w] ??= { width: info.width, height: info.height };
      console.log(`${file} ${info.width}x${info.height} ${(info.size / 1024).toFixed(0)} KB`);
    }
  }
}
// Nav logo: the wordmark of the client's light-background logo (design/img/logo-light.png, 952x170, from the old
// site's public/brand/logo-light.png), tagline cropped off, transparency kept. 740px wide is about 3x the 22px display height.
const LOGO = { src: "design/img/logo-light.png", crop: { left: 5, top: 2, width: 940, height: 84 }, width: 740 };
mkdirSync("public/images/brand", { recursive: true });
const logoBase = () => sharp(LOGO.src).extract(LOGO.crop).resize({ width: LOGO.width });
const logoWebp = await logoBase().webp({ quality: 92, effort: 6 }).toFile("public/images/brand/logo.webp");
const logoPng = await logoBase().png({ compressionLevel: 9 }).toFile("public/images/brand/logo.png");
meta.logo = { width: logoWebp.width, height: logoWebp.height };
console.log(`logo ${logoWebp.width}x${logoWebp.height} webp ${(logoWebp.size / 1024).toFixed(0)} KB, png ${(logoPng.size / 1024).toFixed(0)} KB`);
// Emblem: STAND-IN until the owner supplies the real S emblem from the logo library. It is the S glyph of the wordmark
// (first letter of design/img/logo-light.png), trimmed, never upscaled. Shown in the nav island and used for the favicons.
const EMBLEM_CROP = { left: 5, top: 1, width: 111, height: 86 };
const emblemBase = () => sharp(LOGO.src).extract(EMBLEM_CROP).trim();
const emblemWebp = await emblemBase().webp({ quality: 92, effort: 6 }).toFile("public/images/brand/emblem.webp");
const emblemPng = await emblemBase().png({ compressionLevel: 9 }).toFile("public/images/brand/emblem.png");
meta.emblem = { width: emblemWebp.width, height: emblemWebp.height };
console.log(`emblem ${emblemWebp.width}x${emblemWebp.height} webp ${(emblemWebp.size / 1024).toFixed(0)} KB, png ${(emblemPng.size / 1024).toFixed(0)} KB`);

// Favicons: lime tile, radius 25%, the S in ink at about 62% of the tile height. Colours are read from the tokens file.
const tokens = readFileSync("src/styles/tokens.css", "utf8");
const token = (n) => tokens.match(new RegExp(`--${n}:\\s*(#[0-9a-fA-F]{6})`))[1];
const LIME = token("lime");
const INK = token("ink");
const { data: sData, info: sInfo } = await emblemBase().ensureAlpha().raw().toBuffer({ resolveWithObject: true });
async function favicon(size, file) {
  const h = Math.round(size * 0.62); // 180 -> 112 is the largest step up from the 84px native crop
  const alpha = await sharp(sData, { raw: sInfo }).extractChannel("alpha").resize({ height: h }).toBuffer({ resolveWithObject: true });
  const glyph = await sharp({ create: { width: alpha.info.width, height: alpha.info.height, channels: 3, background: INK } })
    .joinChannel(alpha.data, { raw: { width: alpha.info.width, height: alpha.info.height, channels: 1 } }).png().toBuffer();
  const r = Math.round(size * 0.25);
  const mask = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><rect width="${size}" height="${size}" rx="${r}" fill="#fff"/></svg>`);
  await sharp({ create: { width: size, height: size, channels: 4, background: LIME } })
    .composite([{ input: glyph, gravity: "centre" }, { input: mask, blend: "dest-in" }]).png({ compressionLevel: 9 }).toFile(file);
  console.log(`${file} ${size}x${size}`);
}
await favicon(32, "src/app/icon.png");
await favicon(180, "src/app/apple-icon.png");
const out = `// Generated by scripts/images.mjs. Do not edit.\nexport const images = ${JSON.stringify(meta, null, 2)} as const;\n`;
writeFileSync("src/content/images.ts", out);
